async function main() {
  console.log('🌱 Registering active engineering blog RSS sources...');

  for (const company of SEED_COMPANIES) {
    await prisma.company.upsert({
      where: { slug: company.slug },
      update: {
        name: company.name,
        logoUrl: company.logoUrl,
        rssUrl: company.rssUrl,
        websiteUrl: company.websiteUrl,
        category: company.category,
        description: company.description,
      },
      create: {
        name: company.name,
        slug: company.slug,
        logoUrl: company.logoUrl,
        rssUrl: company.rssUrl,
        websiteUrl: company.websiteUrl,
        category: company.category,
        description: company.description,
      },
    });
  }

  const count = await prisma.company.count();
  console.log(`✅ Seeded ${count} verified engineering blog sources into PostgreSQL!`);

  try {
    const { redis } = await import('../src/lib/redis');
    const keys = await redis.keys('api:*');
    if (keys.length > 0) {
      await redis.del(...keys);
      console.log(`🧹 Cleared ${keys.length} Redis cache keys.`);
    }
  } catch (err) {
    // Ignore Redis errors if Redis is unconfigured
  }
}

main()
  .catch((e) => {
    console.error('❌ Seeding error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });

